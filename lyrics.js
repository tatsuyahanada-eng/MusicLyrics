/* ------------------------------------------------------------
   Next-song peek + prefetch — small chip in the bottom-right
   shows what plays next; tapping it advances. Also warms the
   lyrics cache so the transition is lag-free.
   ------------------------------------------------------------ */
function peekNextSongInfo() {
  if (shuffleActive) {
    if (shuffleFuture.length) return shuffleFuture[shuffleFuture.length - 1];
    if (shuffleQueue.length)  return shuffleQueue[0];
    /* Queue exhausted — the next round will reshuffle from source */
    if (shuffleSource.length) return null;
    return null;
  }
  if (!state.ytQueue.length) return null;
  const nextIdx = (state.ytQueueIdx + 1) % state.ytQueue.length;
  if (nextIdx === state.ytQueueIdx) return null; /* single-item queue */
  const next = state.ytQueue[nextIdx];
  if (next) return { artist: state.currentArtist, title: next.title };
  return null;
}

function updateNextSongPeek() {
  const next = peekNextSongInfo();
  if (elNextSongPeek) {
    if (!next || !next.title) {
      elNextSongPeek.hidden = true;
    } else {
      elNextSongPeek.hidden = false;
      if (elNextSongPeekTitle) elNextSongPeekTitle.textContent = next.title;
      elNextSongPeek.title = `次: ${next.artist ? next.artist + ' - ' : ''}${next.title}`;
    }
  }
  /* Keep the top-of-stage "current → next" display in sync too */
  renderNowPlayingDisplay();
}

function prefetchNextSongLyrics() {
  const next = peekNextSongInfo();
  if (next && next.artist && next.title) {
    /* Fire-and-forget; fetchLyricsCached populates lyricsCache so
       the next handleSongSearch hits it synchronously. */
    fetchLyricsCached(next.artist, next.title).catch(() => {});
  }
  /* Also warm the following shuffle picks so a burst of rapid
     skips still hits the cache instead of re-fetching each time. */
  if (shuffleActive) {
    const upcoming = [];
    if (shuffleQueue.length >= 2) upcoming.push(shuffleQueue[1]);
    if (shuffleQueue.length >= 3) upcoming.push(shuffleQueue[2]);
    for (const s of upcoming) {
      if (s && s.artist && s.title) {
        fetchLyricsCached(s.artist, s.title).catch(() => {});
      }
    }
  }
}

/* ============================================================
   Shuffle play — used by both the artist "ランダム再生" and the
   chart "おまかせ再生". Walks a pool of {artist,title} with full
   back/forward history.
   ============================================================ */
let shuffleActive  = false;
let shuffleKind    = null;   /* 'artist' | 'chart' */
let shuffleSource  = [];     /* full pool */
let shuffleQueue   = [];     /* shuffled, not-yet-played */
let shuffleHistory = [];     /* played songs (oldest first) */
let shuffleFuture  = [];     /* songs backed away from (next-to-pop first) */

function startShufflePlay(songs, kind, statusMsg) {
  if (!songs || !songs.length) {
    setStatus('再生できる曲がありません。', 'error');
    return false;
  }
  shuffleSource  = songs.slice();
  shuffleQueue   = shuffleArray(songs.slice());
  shuffleHistory = [];
  shuffleFuture  = [];
  shuffleActive  = true;
  shuffleKind    = kind;
  updateShuffleUI();
  if (statusMsg) setStatus(statusMsg, 'success');
  playNextInShuffle(true);
  return true;
}

function stopShufflePlay() {
  shuffleActive  = false;
  shuffleKind    = null;
  shuffleSource  = [];
  shuffleQueue   = [];
  shuffleHistory = [];
  shuffleFuture  = [];
  updateShuffleUI();
  updateNextSongPeek();
}

function playNextInShuffle(skipHistory = false) {
  if (!shuffleActive) return;
  /* Push current song to history so 前の曲 can return to it.
     skipHistory is set on the very first pick so the song that
     was playing before shuffle isn't treated as shuffle history. */
  if (!skipHistory && state.currentArtist && state.currentTitle) {
    shuffleHistory.push({ artist: state.currentArtist, title: state.currentTitle });
    if (shuffleHistory.length > 80) shuffleHistory.shift();
  }
  let next;
  if (shuffleFuture.length) {
    next = shuffleFuture.pop();
  } else {
    if (!shuffleQueue.length) {
      if (!shuffleSource.length) { stopShufflePlay(); return; }
      shuffleQueue = shuffleArray(shuffleSource.slice());
    }
    next = shuffleQueue.shift();
  }
  if (!next) { stopShufflePlay(); return; }
  handleSongSearch(next.artist, next.title, { autoplay: true });
}

function playPrevInShuffle() {
  if (!shuffleActive || !shuffleHistory.length) {
    setStatus('戻れる曲がありません。', 'error');
    return;
  }
  if (state.currentArtist && state.currentTitle) {
    shuffleFuture.push({ artist: state.currentArtist, title: state.currentTitle });
  }
  const prev = shuffleHistory.pop();
  handleSongSearch(prev.artist, prev.title, { autoplay: true });
}

