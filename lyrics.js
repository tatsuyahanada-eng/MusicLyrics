/* Strip spacing/punctuation/case so "SUPER BEAVER",
   "superbeaver", "Super-Beaver" all collapse to "superbeaver" */
function normalizeArtistName(s) {
  return (s || '')
    .toLowerCase()
    .replace(/[\s.\-_'"`’()&,!?・·]+/g, '')
    .trim();
}

async function fetchSongsByArtist(artist) {
  const url = `${ITUNES_API}?term=${encodeURIComponent(artist)}&entity=song&limit=100&country=jp`;
  const res  = await fetchWithTimeout(url, 10000);
  if (!res.ok) throw new Error(`iTunes API エラー (HTTP ${res.status})`);
  const data = await res.json();

  const raw = (data.results || []).filter(r => r.trackName && r.artistName);
  if (!raw.length) return [];

  /* Keep the shuffle pool on-artist. Prefer strict equality so
     compilations / "Artist A × Artist B" collabs don't leak in.
     Fall back to prefix match (handles "SUPER BEAVER" vs
     "SUPER BEAVER (スーパー・ビーバー)") and finally to the raw
     list if both filters wipe everything out. */
  const target = normalizeArtistName(artist);
  let matching = raw;
  if (target) {
    const strict = raw.filter(r => normalizeArtistName(r.artistName) === target);
    if (strict.length >= 3) {
      matching = strict;
    } else {
      const prefixed = raw.filter(r => {
        const a = normalizeArtistName(r.artistName);
        return a && (a === target || a.startsWith(target) || target.startsWith(a));
      });
      if (prefixed.length) matching = prefixed;
      else if (strict.length) matching = strict;
    }
  }

  const mapped = matching.map(r => ({
    artist:     r.artistName,
    title:      r.trackName,
    album:      r.collectionName || '',
    durationMs: r.trackTimeMillis || 0,
  }));

  /* Dedupe by normalised title — iTunes returns the same song
     multiple times across different albums / remasters */
  const seen = new Set();
  return mapped.filter(s => {
    const key = (s.title || '').toLowerCase().replace(/\s+/g, ' ').trim();
    if (!key || seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

