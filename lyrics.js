function interpretYouTubeError(status, body) {
  const err   = body.error || {};
  const items = err.errors || [];
  const reason = items[0]?.reason || '';
  const msg    = err.message || `HTTP ${status}`;

  switch (reason) {
    case 'keyInvalid':
      return 'キーが無効です。Google Cloud Console で正しいAPIキーを取得してください。';
    case 'ipRefererBlocked':
    case 'referrerNotAllowed':
      return `リファラ制限でブロックされました。Cloud Console でこのURL (${location.origin}) を許可するか、制限を解除してください。`;
    case 'accessNotConfigured':
    case 'forbidden':
      return 'YouTube Data API v3 が有効化されていません。Google Cloud Console で API を有効にしてください。';
    case 'quotaExceeded':
    case 'dailyLimitExceeded':
      return '本日の API クォータを使い切りました。明日まで待つか、Google Cloud Console でクォータを増やしてください。';
    case 'rateLimitExceeded':
    case 'userRateLimitExceeded':
      return 'YouTube 側の一時的な混雑で自動再試行しましたがブロックが続いています。1〜2分ほど置いてもう一度お試しください。';
  }

  /* Message-based fallback patterns */
  if (/API keys are not supported/i.test(msg)) {
    return 'APIキーがサービスアカウントにバインドされています。Cloud Console →「認証情報」→ 該当キーを編集 →「サービスアカウントを介して API 呼び出しを認証する」のチェックを外して保存してください。';
  }
  if (/API key not valid/i.test(msg)) {
    return 'APIキーが無効です。コピーミスがないか確認し、Cloud Console で再発行してください。';
  }
  if (/has not been used|disabled|consumer/i.test(msg)) {
    return 'YouTube Data API v3 が有効化されていません。Cloud Console の「ライブラリ」で有効にしてください（数分かかる場合あり）。';
  }

  return msg;
}

/* iTunes often returns Japanese songs formatted as "曲名 - Romaji"
   (e.g. "燦然 - Sanzen"). The suffix hurts YouTube search accuracy
   because official MV titles rarely include the romaji. Strip a
   short trailing "- English" cue only when the base title is
   Japanese, so we don't damage titles like "紅蓮華 -CIVIL WAR-"
   or English-only songs. */
function stripRomajiSuffix(title) {
  if (!/[぀-ヿ一-鿿]/.test(title)) return title;
  const m = title.match(/^(.+?)\s+[-–—]\s+([A-Za-z][A-Za-z0-9\s]*)$/);
  if (!m) return title;
  const jp = m[1].trim();
  const en = m[2].trim();
  if (en.split(/\s+/).length <= 2 && en.length <= 20) return jp;
  return title;
}

async function searchYouTube(artist, title) {
  const key = getApiKey();
  if (!key) {
    const e = new Error('YouTubeのAPIキーが未設定です。上部の欄でキーを保存してください。');
    e.code = 'NO_KEY';
    throw e;
  }
  /* Single API call — the strict MV filter (isMvCandidate) below
     drops non-music results, so we no longer need a videoCategoryId
     first pass + fallback. Previously that combination could burn
     200 units per song (Music-cat miss then unrestricted retry);
     one broader query with local filtering halves that. */
  const searchTitle = stripRomajiSuffix(title);
  const params = new URLSearchParams({
    part: 'snippet',
    q: `${artist} ${searchTitle}`,
    type: 'video',
    videoEmbeddable: 'true',
    maxResults: '25',
    key,
  });
  const res = await fetchWithTimeout(`${YT_SEARCH}?${params}`, 12000);
  if (!res.ok) {
    const body = await res.json().catch(() => ({}));
    if ((res.status === 400 || res.status === 403) && !getBuiltinKey()) {
      localStorage.removeItem('yt_api_key_verified');
      setApiKeyStatus('invalid', key);
    }
    throw new Error(interpretYouTubeError(res.status, body));
  }
  const data = await res.json();
  const raw = (data.items || []).map(it => ({
    videoId: it.id.videoId,
    title:   it.snippet.title,
    channel: it.snippet.channelTitle,
    thumb:   it.snippet.thumbnails?.default?.url || '',
  }));
  incrementYtQuotaCounter();
  return rankMusicOnly(raw, artist, title);
}

