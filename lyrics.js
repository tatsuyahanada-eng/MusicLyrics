/* Loose normalisation for relevance checks — lower-case and
   collapse punctuation/whitespace so "Cherry", "cherry", and
   "CHERRY!" all match. */
function normalizeMatchText(s) {
  return (s || '')
    .toLowerCase()
    .replace(/[\s\-_,.'"“”‘’()\[\]{}!?/:;·・、。]+/g, ' ')
    .trim();
}

/* Return true only when the item looks like a real MV: a
   music-video title cue, VEVO channel, or the artist's Official
   Artist Channel. Hard-rejects audio-only markers and non-music
   noise (live/cover/karaoke/#shorts). */
const MV_TITLE_SIGNALS = [
  /official music video/i,
  /music video/i,
  /ミュージックビデオ/,
  /オフィシャルビデオ/,
  /公式ビデオ/,
  /オフィシャル/,
  /公式/,
  /\bmv\b/i,
  /\bm\/v\b/i,
  /\bpv\b/i,
  /\bp\/v\b/i,
  /ｍｖ/,
];

function isMvCandidate(item, artist) {
  const rawT = (item.title   || '').toLowerCase();
  const rawC = (item.channel || '').toLowerCase();
  const cNorm = normalizeMatchText(item.channel);
  const artistN = normalizeMatchText(artist);

  /* Hard reject audio-only tracks — the user asked to skip them */
  if (/official audio|audio only|audio version|audio track|full audio/i.test(rawT)) return false;
  if (/(^|\s)-?\s*topic$/i.test(rawC.trim())) return false;

  /* Hard reject non-music noise */
  if (MV_REJECT_KEYWORDS.some(kw => rawT.includes(kw))) return false;

  const hasMvTitle = MV_TITLE_SIGNALS.some(re => re.test(rawT));
  const isVevo = rawC.includes('vevo');
  const isOfficialArtistChannel = artistN && cNorm === artistN;
  const isOfficialChannel = /official/.test(rawC);
  const isRecordsChannel = /records|entertainment/.test(rawC);

  return hasMvTitle || isVevo || isOfficialArtistChannel
      || isOfficialChannel || isRecordsChannel;
}

/* Rank YouTube results as MVs. MV filter is now strict — if the
   pool contains no real MV candidates, an empty array is returned
   so the app shows "no YouTube results" rather than playing a
   half-relevant audio track. Within the MV set the same scoring
   still orders best-matches first. */
function rankMusicOnly(items, artist, title) {
  const scored = items.map(it => ({
    it,
    s: scoreMusicCandidate(it, artist, title),
    isMv: isMvCandidate(it, artist),
  }));
  scored.sort((a, b) => b.s - a.s);
  const mvOnly = scored.filter(x => x.isMv).slice(0, 10);
  if (mvOnly.length > 0) return mvOnly.map(x => x.it);

  /* Strict MV filter dropped everything. That's fine for random /
     おまかせ playback because the next song will retry, but it
     leaves single-song taps with silence — the top candidate
     from the artist's iTunes list often isn't a real MV (album
     versions, deep cuts, live editions) and the user tapped it
     *specifically* to hear it. Fall back to the highest-scoring
     candidates that still clearly match artist + title so a tap
     always produces sound. Threshold s >= 6 keeps unrelated
     videos out (exact title +10, partial title +6, partial artist
     ±2–6). */
  const fallback = scored.filter(x => x.s >= 6).slice(0, 10);
  return fallback.map(x => x.it);
}

function scoreMusicCandidate(item, artist, title) {
  const rawT = (item.title   || '').toLowerCase();
  const rawC = (item.channel || '').toLowerCase();
  const tNorm = normalizeMatchText(item.title);
  const cNorm = normalizeMatchText(item.channel);
  const artistN = normalizeMatchText(artist);
  const titleN  = normalizeMatchText(title);

  let s = 0;

  /* --- Relevance signals (dominant, so wrong-video results sink) --- */
  if (titleN) {
    if (tNorm.includes(titleN)) {
      s += 10;                       /* exact title phrase in the video title */
    } else {
      /* Partial match: how many words of the song title appear? */
      const words = titleN.split(/\s+/).filter(w => w.length >= 2);
      if (words.length) {
        let hit = 0;
        for (const w of words) if (tNorm.includes(w)) hit++;
        const ratio = hit / words.length;
        if (ratio >= 0.8)      s += 6;
        else if (ratio >= 0.5) s += 2;
        else                   s -= 8;   /* almost nothing matches — probably wrong */
      }
    }
  }

  if (artistN) {
    /* Exact channel-name match usually means Official Artist
       Channel, so give it a bigger nudge than just contains(). */
    if (cNorm === artistN) s += 4;
    if (tNorm.includes(artistN) || cNorm.includes(artistN)) s += 6;
    else {
      /* Try individual words of the artist name */
      const words = artistN.split(/\s+/).filter(w => w.length >= 2);
      if (words.length) {
        let hit = 0;
        for (const w of words) if (tNorm.includes(w) || cNorm.includes(w)) hit++;
        if (hit === 0)                    s -= 5;
        else if (hit < words.length / 2)  s -= 2;
        else                              s += 2;
      }
    }
  }

  /* --- MV-quality boosts (biggest positive signal) --- */
  for (const [kw, w] of MV_TITLE_BOOST)   if (rawT.includes(kw)) s += w;
  for (const [kw, w] of MV_CHANNEL_BOOST) if (rawC.includes(kw)) s += w;

  /* --- Audio-only markers subtract (we're routing users to MVs) --- */
  for (const [kw, w] of AUDIO_ONLY_PENALTY) if (rawT.includes(kw)) s += w;

  /* --- YT-Auto Topic channels are audio-only — tiny nudge only --- */
  for (const [kw, w] of YTM_CHANNEL_BOOST) if (rawC.includes(kw)) s += w;

  /* --- Non-music markers: soft penalty only --- */
  for (const kw of MV_REJECT_KEYWORDS) {
    if (rawT.includes(kw)) s -= 3;
  }

  return s;
}

