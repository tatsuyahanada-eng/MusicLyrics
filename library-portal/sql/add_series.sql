-- ============================================================
--  ライブラリポータル — シリーズ（関連する資料をまとめる名前）を追加
--
--  すでに稼働しているデータベースに対して、1回だけ実行してください。
--  （新規に schema.sql から作る場合は、この作業は不要です）
--
--  ★★ 実行する前に必ず「データベースを選んだ状態」にしてください ★★
--
--    phpMyAdmin を開く
--      → 画面左の一覧から、使っているデータベース名をクリック
--         （ここをクリックせずに実行すると
--           「#1046 データベースが選択されていません」になります）
--      → 画面上部が「サーバー … › データベース … 」の表示に変わったのを確認
--      → 上の「SQL」タブをクリック
--      → このファイルの内容を貼り付けて「実行」
--
--  用途：
--    「無線チャンネル変更」のように、同じ対象に関する
--    アプリ・マニュアル・資料をひとまとまりとして扱えるようにします。
--
--  よくあるエラーと対処：
--    #1046 データベースが選択されていません
--        → 上記のとおり、左の一覧でデータベース名をクリックしてから実行
--    #1060 Duplicate column name 'series'
--        → すでに追加済みです。そのままで問題ありません
--    #1061 Duplicate key name 'idx_items_series'
--        → すでに追加済みです。そのままで問題ありません
-- ============================================================

SET NAMES utf8mb4;

-- 念のための確認用：実行前にこれだけを流すと、対象のデータベース名が出ます。
-- 空欄や NULL が返る場合は、データベースが選択されていません。
-- SELECT DATABASE();

ALTER TABLE lp_items
  ADD COLUMN series VARCHAR(60) NULL COMMENT 'シリーズ（関連する資料をまとめる名前）' AFTER category;

ALTER TABLE lp_items
  ADD INDEX idx_items_series (series);

-- 追加できたか確認する（series の行が1件出れば成功です）
SHOW COLUMNS FROM lp_items LIKE 'series';
