-- ============================================================
--  ライブラリポータル — シリーズ（関連する資料をまとめる名前）を追加
--
--  すでに稼働しているデータベースに対して、1回だけ実行してください。
--  （新規に schema.sql から作る場合は、この作業は不要です）
--
--  ============================================================
--  ★ 手順は2つだけです ★
--
--   【1】 下の «ここにデータベース名» を、実際の名前に書き換える
--
--         データベース名は、サーバー上の includes/config.php の
--           'db_name' => 'アカウント名_library',
--         に書いてある値です（phpMyAdmin の画面左の一覧にも出ています）。
--
--         例）データベース名が welsys_library の場合
--             USE `welsys_library`;
--
--   【2】 phpMyAdmin の「SQL」タブに貼り付けて実行する
--
--         USE を書いているので、サーバーの画面・データベースの画面の
--         どちらから実行しても通ります。
--  ============================================================
--
--  用途：
--    「無線チャンネル変更」のように、同じ対象に関する
--    アプリ・マニュアル・資料をひとまとまりとして扱えるようにします。
--
--  出たときに気にしなくてよいエラー：
--    #1060 Duplicate column name 'series'       → すでに追加済みです
--    #1061 Duplicate key name 'idx_items_series' → すでに追加済みです
--
--  それ以外のエラー：
--    #1046 データベースが選択されていません
--        → 下の USE 行を書き換え忘れているか、行頭に -- が付いたままです
--    #1049 Unknown database
--        → USE に書いた名前が違います。config.php の db_name を確認してください
-- ============================================================

SET NAMES utf8mb4;

-- ↓↓↓ ここを実際のデータベース名に書き換えてください ↓↓↓
USE `«ここにデータベース名»`;
-- ↑↑↑ ここを実際のデータベース名に書き換えてください ↑↑↑

ALTER TABLE lp_items
  ADD COLUMN series VARCHAR(60) NULL COMMENT 'シリーズ（関連する資料をまとめる名前）' AFTER category;

ALTER TABLE lp_items
  ADD INDEX idx_items_series (series);

-- 追加できたか確認する（series の行が1件表示されれば成功です）
SHOW COLUMNS FROM lp_items LIKE 'series';
