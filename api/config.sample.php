<?php
/**
 * 領収書AI読み取りの設定ファイル（サンプル）
 *
 * 【初回の設定】
 *   1. このファイルを同じフォルダ（api/）に config.php という名前でコピーする
 *   2. gemini_api_key に Google AI Studio で発行したAPIキーを貼り付けて保存する
 *   3. 画面の「🔌 接続テスト」ボタンで「接続OK」と出ればOK
 *
 * 【APIキーを変更するとき】
 *   config.php の gemini_api_key を新しいキーに書き換えて上書き保存するだけで、すぐに反映されます。
 *   index.html や receipt.php を編集する必要はありません。
 *   変更後は「🔌 接続テスト」で新しいキー（末尾4桁）が有効か確認してください。
 *
 * 【モデルを変更するとき】
 *   model を新しいモデル名に書き換えます（旧モデルの提供終了時など）。
 *
 * 【1日に読み取れる回数を増やす】
 *   無料枠の「1日あたりの回数」の上限は、モデルごとに別々に数えられます。
 *   主モデル（model）が上限に達すると、予備のモデル（fallback_models）へ自動で切り替わり、
 *   上限に達したモデルはその日のうちは使いません。何も設定しなくても、初期設定の予備モデルが使われます。
 *   - 予備のモデルを変える：fallback_models に、使いたい順にモデル名を書く（モデル名は Google AI Studio で確認）
 *   - 予備を使わず主モデルだけにする：'fallback_models' => []
 *   - 全体の順番を自分で決める：models に全部書く（model と fallback_models は無視されます）
 *   存在しないモデル名を書いても、自動で飛ばされるだけでエラーにはなりません。
 *   さらに、複数の領収書を1回のAI呼び出しにまとめて送るので、枚数が多いほど回数を節約できます（max_files_per_request）。
 *   画面の「ダブルチェック」は初期設定の「自動」だと、読み取りに自信があるものは2回目を省略するため、回数をさらに節約できます。
 *   ※予備のモデルは主モデルより読み取り精度が低い場合があります。画面に「予備のモデルも使いました」と出たときは、
 *     いつもより丁寧に内容を確認してください。精度を優先する場合は、有料枠にして主モデルだけで使うのがおすすめです。
 *
 * config.php は api/.htaccess で外部から直接開けないよう保護されています。
 * APIキーをGitなどにコミットしないでください（.gitignore で config.php は除外済み）。
 */
return [
    // Gemini APIキー（必須）
    'gemini_api_key' => 'YOUR_GEMINI_API_KEY',

    // 主モデル（省略時は gemini-3.8-flash）
    'model' => 'gemini-3.8-flash',

    // 予備モデル（主モデルが1日の上限に達したときに、上から順に使う。省略時は下の3つ。[] で予備なし）
    'fallback_models' => ['gemini-3.7-flash', 'gemini-3.6-flash', 'gemini-3.5-flash-lite'],

    // 領収書を何枚まとめて1回のAI呼び出しで読み取るか（1〜6。省略時は4）
    // 多いほど1日に使う回数が減ります。まとめた画像の内容が取り違えられるように感じたら、1にしてください（1枚ずつ読み取り）。
    'max_files_per_request' => 4,
];
