<?php
/**
 * 領収書AI読み取りの設定ファイル（サンプル）
 *
 * 【初回の設定】
 *   1. このファイルを同じフォルダ（api/）に config.php という名前でコピーする
 *   2. gemini_api_key に Google AI Studio で発行したAPIキーを貼り付けて保存する
 *   3. 画面の「🔌 接続テスト」ボタンで「接続OK」と出ればOK
 *
 * 【APIキーを変更するとき】
 *   config.php の gemini_api_key を新しいキーに書き換えて上書き保存するだけで、すぐに反映されます。
 *   index.html や receipt.php を編集する必要はありません。
 *   変更後は「🔌 接続テスト」で新しいキー（末尾4桁）が有効か確認してください。
 *
 * 【モデルを変更するとき】
 *   model を新しいモデル名に書き換えます（旧モデルの提供終了時など）。
 *
 * 【1日に読み取れる回数を増やす】
 *   無料枠の「1日あたりの回数」の上限は、モデルごとに別々に数えられます。
 *   主モデル（model）が上限に達すると、予備のモデル（fallback_models）へ自動で切り替わり、
 *   上限に達したモデルはその日のうちは使いません。何も設定しなくても、初期設定の予備モデルが使われます。
 *   - 予備のモデルを変える：fallback_models に、使いたい順にモデル名を書く（モデル名は Google AI Studio で確認）
 *   - 予備を使わず主モデルだけにする：'fallback_models' => []
 *   - 全体の順番を自分で決める：models に全部書く（model と fallback_models は無視されます）
 *   存在しないモデル名を書いても、自動で飛ばされるだけでエラーにはなりません。
 *
 * 【Gemini が混雑しているとき】
 *   新しいモデルは、無料枠だと混雑（503）や、応答が返らない状態になることがあります（Google側の混雑で、こちらでは直せません）。
 *   そのため、主モデルから15秒たっても答えが返らないときは、予備のモデルでも同時に読み始めて、先に終わった方を使います。
 *   混雑しているモデルは、続くほど長く（1分→4分→12分）後回しにして、予備のモデルから読みます。
 *   最後の予備として、最新の Flash-Lite 系のモデルを自動で探して追加します（lite_fallback で無効化）。精度は下がりやすいため、
 *   使ったときは画面に「予備のモデルで読み取りました」と出ます。
 *   画面の「ダブルチェック」は初期設定の「自動」だと、読み取りに自信があるものは2回目を省略するため、回数を節約できます。
 *   max_files_per_request を増やすと複数の領収書を1回にまとめて送るので回数は減りますが、読み取りの精度が下がり、時間切れも起きやすくなります
 *   （まとめ読みが失敗したときは、画面が自動で1枚ずつ読み直します）。通常は1のままをおすすめします。
 *   ※予備のモデルは主モデルより読み取り精度が低い場合があります。画面に「予備のモデルも使いました」と出たときは、
 *     いつもより丁寧に内容を確認してください。精度を優先する場合は、有料枠にして主モデルだけで使うのがおすすめです。
 *
 * config.php は api/.htaccess で外部から直接開けないよう保護されています。
 * APIキーをGitなどにコミットしないでください（.gitignore で config.php は除外済み）。
 */
return [
    // Gemini APIキー（必須）
    'gemini_api_key' => 'YOUR_GEMINI_API_KEY',

    // 主モデル（省略時は gemini-3.8-flash）
    'model' => 'gemini-3.8-flash',

    // 予備モデル（主モデルが1日の上限に達したとき・混雑しているときに、上から順に使う。省略時は下の2つ。[] で予備なし）
    // 初期設定は Flash 系の2つです。その後ろに、最新の Flash-Lite 系が「最後の予備」として自動で追加されます（下の lite_fallback）。
    'fallback_models' => ['gemini-3.7-flash', 'gemini-3.6-flash'],

    // 最後の予備として、最新の Flash-Lite 系のモデルを自動で足すか（省略時は true）。
    // Flash 系がすべて混雑・上限のときでも読み取れるようにするためです。精度は下がりやすいので、使った分は画面に表示されます。
    // 使いたくないときは false にしてください（models を直接指定したときは、自動では足しません）
    'lite_fallback' => true,

    // 領収書を何枚まとめて1回のAI呼び出しで読み取るか（1〜6。省略時は1）
    // 精度を優先して、初期設定は1枚ずつです（Googleの資料でも、文字の読み取りは1枚ずつの方が精度が良いとされています）。
    // 回数を節約したいときだけ増やしてください（増やすと精度が下がり、時間切れも起きやすくなります。
    // まとめ読みが失敗したときは、画面が自動で1枚ずつ読み直します）。通常は 1 のままをおすすめします。
    'max_files_per_request' => 1,

    // 読み取り結果の要約を api/data/log.jsonl に記録するか（原因調査用。画像・APIキーは記録しません。直近300件）
    'log_requests' => true,

    // 画像1枚の呼び出しで応答を待つ上限（秒。省略時は60。最低5）。まとめ読みは、2枚目以降1枚ごとに25秒ずつ延びます。
    // これを超えたら、そのモデルを後回しにして、次のモデルに切り替えます
    'request_timeout' => 60,

    // 主モデルから何秒たっても答えが返らなければ、次のモデルでも同時に読み始めるか（秒。省略時は15。3〜60）
    // 先に終わった方を使います。小さくすると速くなりますが、予備のモデルの回数（無料枠の1日の上限）を使いやすくなります
    'hedge_after' => 15,

    // 画面が、AI呼び出しの開始を何秒以上あけるか（秒。省略時は12。0〜60）
    // 無料枠は、1分に5回までのモデルが多いためです。有料枠にしたら 0 にすると、続けて読み取るときが速くなります
    'min_call_interval' => 12,

    // AIの考える量。1回目の読み取り（'low' が既定。'minimal' / 'low' / 'medium' / 'high'。'' にするとGeminiの既定＝high）
    // 考える量が多いほど、1枚あたりの時間が長くなり、応答が返らない（時間切れ）ことが増えます。
    // 領収書の読み取りは単純な作業なので、'low' で十分です。金額の根拠の照合と、ダブルチェックで精度を補います
    'thinking_level' => 'low',

    // ダブルチェック（2回目以降の読み取り）の考える量（'medium' が既定。1回目より低くはなりません。'' なら1回目と同じ）
    // 1回目で自信のない領収書だけが2回目に進むので、ここは丁寧に読ませます
    'thinking_level_recheck' => 'medium',
];
